#: 「可疑」分两档，体检面板据此决定默认勾不勾：
#:   high = 几乎确定是垃圾，默认勾上
#:   mid  = 像垃圾，但作者可能真有理由，默认不勾、只列出来让他自己看
_HIGH = "high"
_MID = "mid"


def _bad(kind: str, reason: str, severity: str = _HIGH) -> dict:
    return {"ok": False, "kind": kind, "reason": reason, "severity": severity}


_OK = {"ok": True, "kind": None, "reason": None, "severity": None}


def _looks_redup(name: str) -> bool:
    """叠字形态。

    只拦两种，**刻意放过两字叠名**（娜娜、双双、芳芳都是正常小名）：
    - 同一个字叠三次以上（不不不、啊啊啊）—— 中文里没人这么起名
    - 两字叠且字本身是拟声字（呜呜、咚咚、哈哈）
    - AABB（嘟嘟囔囔）—— 叠词成语，不是名字
    """
    if len(set(name)) == 1:
        return len(name) >= 3 or name[0] in ONOMATOPOEIA_CHARS
    if len(name) == 4 and name[0] == name[1] and name[2] == name[3]:
        return True
    return False


def judge_name(name: str, *, type_key: str | None = None,
               min_len: int = 2, max_len: int | None = None) -> dict:
    """给一个名字做体检。

    返回 `{"ok", "kind", "reason", "severity"}`：
    - `ok=True` 表示没看出问题
    - 否则 `kind` 是问题分类、`reason` 是可以直接给人看的理由、
      `severity` 是 `"high"`（确定）或 `"mid"`（可疑）

    **判定分类型**（`type_key`）—— 这是这套规则最容易出错的地方：
    人名的形态规则（副词 / 动词短语 / 语气词收尾 / 虚词头尾）套到机构名上
    会成片误伤（「圣裁决所」「钟楼酒吧」「别动队」「对内情报司」都是正经名）。
    所以：
    - character（或不传）：跑全部规则，长度上限 8
    - 其他类型：只跑跨类型通用规则（空 / 太短 / 太长 / 非法字符 / 叠字 / 语气词 / 疑问词 / 程度短语），
      长度上限放宽到 20~24，允许全角括号与 `-` 层级

    `max_len` 显式给了就用给的（抽取器那边只找 2~4 字的专名，会传 `max_len=4`）。
    """
    raw = (name or "").strip()
    person = _is_person(type_key)
    if max_len is None:
        max_len = _MAX_LEN.get(type_key, _DEFAULT_MAX) if type_key else 8
    if not raw:
        return _bad("empty", "名字是空的")
    if len(raw) < min_len:
        return _bad("too_short", f"只有 {len(raw)} 个字，太短，多半是切出来的碎片")
    # 带间隔号的西方译名可以很长（「雅尔娜·提亚尔蒂斯」），每个 · 多给 4 字余量，
    # 否则真名会栽在长度上 —— 这是筛查里最不该犯的错。
    if len(raw) > max_len + 4 * raw.count("·"):
        return _bad("too_long", f"{len(raw)} 个字，超出这类名字的常见长度")
    allowed = rf"[{_CN}A-Za-z0-9·.\-—]+"
    if not person:
        # 机构 / 地名允许全角括号与竖线斜杠（「战士（魔法）-武器」「四院一军一所」）
        allowed = rf"[{_CN}A-Za-z0-9·.\-—{_EXTRA_CHARS}]+"
    if not re.fullmatch(allowed, raw):
        return _bad("charset", "含有不该出现在专名里的字符")

    # ---- 跨类型通用规则（人名 / 机构名 / 地名都适用） ----
    if raw in INTERJECTIONS:
        return _bad("interjection", "是语气词 / 拟声词")
    if _looks_redup(raw):
        return _bad("redup", "同一个字反复叠用，像拟声词或结巴")
    if raw in INTERROGATIVES or raw.endswith(_INTERROGATIVE_SUFFIX):
        return _bad("interrogative", "是疑问词，多半从问句里切下来的")
    if raw.startswith(_DEGREE_PREFIX):
        return _bad("degree", "以程度副词开头，是修饰语连形容词被一起切下来的")

    # 非人名类型到此为止 —— 下面的规则是按人名形态写的，套机构名会成片误伤
    if not person:
        return dict(_OK)

    # ---- 以下仅对人名生效 ----
    if raw in ADVERBS:
        return _bad("adverb", "是副词，应该是修饰语被误切成名字")
    if raw in VERB_PHRASES or raw.endswith(_TREND_TAILS):
        return _bad("verb_phrase", "是动词短语（动作），不是名字")
    if raw.endswith("们"):
        return _bad("plural", "以「们」结尾，是复数泛称")
    if raw.endswith(_TAIL_PARTICLES):
        return _bad("particle", "以语气助词收尾，是对话里切出来的短句")

    # 代词收尾 —— 「白她」「李他」：说话动词锚点把人名和后面的代词粘在一起了。
    # 真人名末字绝不可能是这七个字（「省」是地名后缀，特意不收——X省是地区）。
    if len(raw) >= 2 and raw[-1] in "他她你我谁这那它":
        return _bad("pronoun_tail", "以代词收尾，是人名粘着代词被切下来的")
    # 叠动词 —— 「摆摆手」「点点头」：三字、前两字相同、第三字是身体/动作宾语。
    # 第三字必须是这类字才拦（「芭芭拉」「贝贝儿」这类叠字真名第三字不是），标「可疑」。
    if len(raw) == 3 and raw[0] == raw[1] and raw[2] != raw[0] and raw[2] in _VV_BODY_TAILS:
        return _bad("verb_redup", "前两字重叠、末字是身体部位，像「摆摆手」这类动作短语", _MID)

    # ---- 以下误伤风险更高，只标「可疑」 ----
    if raw in PRONOUNS:
        return _bad("pronoun", "是代词或泛称，不是具体某个人", _MID)
    if raw in GENERIC_WORDS:
        return _bad("generic", "是通用名词，不是专名", _MID)
    if raw.startswith(_NEG_PREFIX):
        return _bad("negation", "以否定词开头，像句子片段")
    # 语气词打头 —— 「啊这」「嗯那」。这几个字没有作姓氏的（「阿」除外，阿福是真名）。
    if len(raw) >= 2 and raw[0] in "啊哎唉哦噢喔嗯呃":
        return _bad("interj_head", "以语气词开头，像对话里切出来的", _MID)
    # 衔接副词打头 —— 「便连」「便有一」：叙述句「便有一…」被整段切下。
    # 只收绝不入名的四个字（「曾」是真姓——曾静，不收）。
    if len(raw) >= 2 and raw[:1] in ("便", "又", "就", "已"):
        return _bad("adv_head", "以衔接副词开头，像叙述句碎片", _MID)
    # 副词收尾 —— 「白重新」：人名粘着后面的副词。两字以上副词收尾的真人名找不出来。
    if len(raw) >= 3 and any(len(a) >= 2 and raw.endswith(a) and len(raw) > len(a)
                             for a in ADVERBS):
        return _bad("adv_tail", "以副词收尾，像人名粘着修饰语被切下来的", _MID)
    if raw.startswith(BAD_PREFIX):
        return _bad("bad_prefix", "以量词 / 指代开头，像被切碎的短语", _MID)
    # 「的」夹在中间 —— 「蝴蝶的女」「贵的议长」。中文专名基本不含「的」。
    if "的" in raw[1:]:
        return _bad("fragment", "中间夹着「的」，是句子碎片", _MID)
    if raw[0] in BAD_HEAD:
        return _bad("bad_head", "以虚词 / 代词开头", _MID)
    # 「末字是虚词」只对三字以上生效 —— 两字名的末字是单字名，不能查（见 _BAD_TAIL_HARD）
    if len(raw) >= 3 and raw[-1] in _BAD_TAIL_HARD:
        return _bad("bad_tail", "以虚词收尾，是句子碎片", _MID)
    return dict(_OK)


def is_plausible(name: str, *, max_len: int = 4) -> bool:
    """抽取器用的简版门槛：只看能不能过。"""
    return judge_name(name, max_len=max_len)["ok"]
